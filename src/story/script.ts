/**
 * 70歳を過ぎた自分は、何回目の電話かを覚えていない（あなたが教える）。
 * はっきりとは言わないが、少しずつ記憶が遠くなっていることを感じさせる、少しさみしい場面。
 * （2005年生まれなら 50・60年後）
 */
const forgetsCount = (c: CallContext) => (c.tier === 'elder' || c.tier === 'eighty' || c.tier === 'ninety') && c.futureAge >= 70

/**
 * 年を重ねたことを、さりげなく感じさせる一言（どの年代にも、その年代なりの老い）。
 * 体のことを言い切らず、本人の実感として短く話す。
 */
const agingLine = (c: CallContext): Variant[] => {
  switch (c.tier) {
    case 'young':
      return [t('最近、夜ふかしすると、次の日に残るようになって{ね}。……そっちは、まだ平気{でしょ}？')]
    case 'middle':
      return [t('近ごろ、駅の階段で、ひと息つきたくなる{よ}。……そっちは、まだ身軽{でしょ}。')]
    case 'elder':
      return c.futureAge >= 70
        ? [t('このごろ、人の名前が、すっと出てこないことがあって{ね}。……でも、そっちの声は、ちゃんとわかる{よ}。')]
        : [t('近ごろは、朝早くに目が覚めてしまって{ね}。……そのぶん、空をよく見る{よ}。')]
    case 'eighty':
      return [t('……耳が、少し遠くなって{ね}。ゆっくり話してくれると、うれしい{よ}。')]
    case 'ninety':
      return [t('……ごめん{ね}、声が小さくて。長く話すと、すぐに息が切れてしまう{よ}。')]
    default:
      return []
  }
}

/**
 * 子孫が出たとき：あなた（ご先祖さま）が「過去の自分と電話で話した」と、家族から聞いたような気がする、という一言。
 * 孫・ひ孫は、あなたの性別で「おじいちゃん／おばあちゃん」と呼ぶ。その先の代や、性別を答えていないときは「うちに伝わる話」として話す。
 */
function heardLine(c: CallContext): string {
  const g = c.gender === 'male' ? 'おじいちゃん' : c.gender === 'female' ? 'おばあちゃん' : null
  const who = g && c.relation === '孫' ? g : g && c.relation === 'ひ孫' ? `ひい${g}` : null
  return who
    ? `……そういえば、${who}から聞いたことがあるような……。過去の自分と、電話で話したことがあるって……。`
    : '……そういえば、うちに昔から伝わる話があるような……。ご先祖さまが、過去の自分と電話で話したことがあるって……。'
}

/** 前回の電話から、どれくらいたったか */
const sinceLine = (c: CallContext): Variant => {
  const h = c.prev?.hoursAgo ?? 0
  if (h < 20) return t('前の電話から、まだ少ししかたってない{ね}。')
  const d = Math.max(1, Math.round(h / 24))
  return t(`前の電話から、${d}日{だね}。`)
}

/** 前回の話題に触れる（書いた言葉があれば、それも） */
const memoLines = (c: CallContext): Variant[] => {
  const noun = c.prev?.topic ? TOPIC_NOUN[c.prev.topic] : undefined
  const text = c.prev?.topicText
  const lines: Variant[] = []
  if (noun) lines.push(t(`この前は、${noun}の話をした{ね}。`, undefined, `この前は、${noun}の話をした{ね}。`))
  if (text) lines.push(t(`「${text}」のこと、こっちも覚え{てる}{よ}。`, undefined, `「${text}」……ちゃんと覚え{てる}{よ}。`))
  return lines
}

