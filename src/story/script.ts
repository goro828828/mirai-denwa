/**
 * 会話シナリオ（分岐型）
 *
 * 作品の核：
 *   「懐かしむ」という、本来は過去に対してしかできないことを、現在進行形で体験する。
 *   未来の自分は、プレイヤーの「今」を、すでに懐かしい思い出として語る。
 *   プレイヤーは、その視点を借りて、今日を少しだけ先回りして懐かしむ。
 *
 * 電話の相手は、10・20・30・40・50・60年後の自分（通話ごとにランダム）。
 * 話し方は3段階：10年後＝気さく／20・30年後＝落ち着いた大人／40〜60年後＝年を重ねた穏やかな話し方。
 * 年齢は、口調・間・視点で感じさせる。病気や家族構成など、未来の出来事は断定しない。
 *
 * 書き方のルール（text.ts も参照）
 * - v(標準語, 関西弁, 博多弁)、a(10年後, 20〜30年後, 40〜60年後)
 * - 会話の内容と感情の流れは、どの地域・どの年代でも共通にする。
 * - 人間関係が失われると決めつけない。説教や押しつけにしない。
 * - 一人称はなるべく使わない（性別を推測しないため）。
 *
 * ※ 会話の全文と分岐数は仕様上「未確定」。差し替え前提の稿。
 */
