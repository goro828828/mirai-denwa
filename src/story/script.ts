/**
 * 会話シナリオ（分岐型）
 *
 * 作品の核：
 *   「懐かしむ」という、本来は過去に対してしかできないことを、現在進行形で体験する。
 *   未来の自分は、プレイヤーの「今」を、すでに懐かしい思い出として語る。
 *   プレイヤーは、その視点を借りて、今日を少しだけ先回りして懐かしむ。
 *
 * 書き方のルール
 * - v(標準語, 関西弁, 博多弁)。関西弁・博多弁を省略すると標準語を使う。
 * - 会話の内容と感情の流れは、どの地域でも共通にする。
 * - 懐かしさは「未来の自分が今そう感じている」として語る。未来の出来事は断定しない。
 * - 人間関係が失われると決めつけない。説教や押しつけにしない。
 * - 一人称はなるべく使わない（性別を推測しないため）。
 *
 * ※ 会話の全文と分岐数は仕様上「未確定」。差し替え前提の稿。
 */
import type { CallContext } from './engine'

export type Text = string | ((c: CallContext) => string)
export interface Variant {
  standard: Text
  kansai?: Text
  hakata?: Text
}
export const v = (standard: Text, kansai?: Text, hakata?: Text): Variant => ({ standard, kansai, hakata })

export interface Choice {
  label: Text
  value: string
  /** 選んだあとに未来の自分が返す言葉 */
  reply?: Variant[]
  next?: string
}

export interface StoryNode {
  id: string
  /** 未来の自分の台詞（順番に表示） */
  say?: (c: CallContext) => Variant[]
  /** 記録用の質問文（通話履歴に保存される） */
  question?: string
  answerKey?: string
  choices?: (c: CallContext) => Choice[]
  input?: { key: string; prompt: string; placeholder: string; maxLength: number }
  /** 自由入力のあとの返答 */
  inputReply?: (value: string) => Variant[]
  next?: string
  /** 特別な演出 */
  effect?: 'voice' | 'lowcard' | 'final' | 'listen'
}

