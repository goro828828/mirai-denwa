export interface Choice {
  label: Text
  value: string
  /** 選んだあとに未来の自分が返す言葉 */
  reply?: Variant[]
  next?: string
}

export interface InputDef {
  key: string
  prompt: string
  placeholder: string
  maxLength: number
}

export interface StoryNode {
  id: string
  /** 未来の自分の台詞（順番に表示） */
  say?: (c: CallContext) => Variant[]
  /** 記録用の質問文（通話履歴に保存される） */
  question?: string | ((c: CallContext) => string)
  answerKey?: string
  choices?: (c: CallContext) => Choice[]
  input?: InputDef | ((c: CallContext) => InputDef)
  /** 自由入力のあとの返答 */
  inputReply?: (value: string, c: CallContext) => Variant[]
  /** 次の場面（会話の種類で変える場合は関数） */
  next?: string | ((c: CallContext) => string)
  /** 特別な演出 */
  effect?: 'voice' | 'lowcard' | 'final' | 'listen'
  /**
   * 選択肢のあとの「自分の言葉で答える」（4択＋自由回答）。false なら出さない（最初のあいさつなど）。
   * 省略時は、書いた言葉をそのまま受けとめる返事（freeDefault）。
   */
  free?: false | FreeDef
}

export interface FreeDef {
  /** 書いた言葉に返す台詞 */
  reply: (value: string, c: CallContext) => Variant[]
  /** answerKey に入れる値（あとの会話・最後のメッセージで使う分類） */
  as?: string
  /** 書いた言葉を、そのまま入れておく answers のキー */
  textKey?: string
  /** 通話履歴に残す質問（ノードに question がないとき） */
  question?: string
  placeholder?: string
  /** 次の場面（省略時はノードの next） */
  next?: string | ((c: CallContext) => string)
}

