/**
 * 最後のメッセージ（カードに印字される）
 *
 * 未来の自分が「今日」をすでに懐かしんでいる、という視点で語る。短く（2文まで）。
 * 自由記述の気持ち（feeling）に手がかりがあればそれを優先し、なければ選んだ気持ち（mood）を軸にする。
 * 自由記述の本文はカードに載せない（共有カードに個人的な回答を出さないため）。
 */
import type { CallContext } from './engine'
import { t, type Variant } from './text'

export type FeelingCategory = 'calm' | 'tired' | 'anxious' | 'excited' | 'unsure' | 'lonely' | 'sad' | 'happy' | 'grateful'

/** 自由記述の気持ちから、言葉の手がかりで分類する（AIは使わない簡易判定）。手がかりがなければ選択肢の気持ち */
const FEELING_KEYWORDS: [FeelingCategory, RegExp][] = [
  ['sad', /悲し|かなし|つら|辛|泣|しんど|きつ|落ち込|へこ|凹/],
  ['lonely', /寂し|さみし|さびし|孤独|ひとりぼっち|一人ぼっち/],
  ['anxious', /不安|心配|こわ|怖|焦|あせ|緊張|モヤ|もや/],
  ['tired', /疲|つかれ|眠|ねむ|だる|休みたい/],
  ['grateful', /ありがと|感謝|おかげ/],
  ['happy', /嬉し|うれし|楽し|たのし|幸せ|しあわせ|最高|好き/],
  ['excited', /わくわく|ワクワク|楽しみ|たのしみ|ドキドキ|どきどき/],
  ['calm', /穏やか|おだやか|落ち着|のんびり|ほっと|ゆったり/],
]

export function feelingCategory(c: CallContext): FeelingCategory {
  const text = c.answers.feeling ?? ''
  // 「楽しみ」は happy より excited を優先
  if (/楽しみ|たのしみ/.test(text)) return 'excited'
  for (const [cat, re] of FEELING_KEYWORDS) if (re.test(text)) return cat
  return (c.answers.mood as FeelingCategory) || 'calm'
}

const WHO: Record<string, string> = { family: '家族と', friend: '友だちと', peer: 'まわりの人と', alone: 'ひとりで' }

export function finalMessage(c: CallContext): Variant {
  const name = c.name
  const who = WHO[c.answers.people] ?? ''
  const passion = c.topic === 'passion' && c.answers.topicText ? `${c.answers.topicText}も、` : ''

  // t(10年後, 20〜30年後, 40〜60年後, 10年前, 100年後)
  switch (feelingCategory(c)) {
    case 'lonely':
      return t(
        `さみしかった日も、こっちからは少し懐かしい。誰かを大事に思える${name}の、しるし{だよ}。`,
        undefined,
        `さみしかった日のことも、今は少し懐かしい{よ}。人を大事に思える、${name}の証{だよ}。`,
        `さみしい日もあるんだ{ね}。……それでも電話に出てくれた${name}が、こっちの自慢{だよ}。`,
        `さみしかった日も、100年たつと、やさしい思い出になる{よ}。人を大事に思える${name}の証{だよ}。`,
      )
    case 'sad':
      return t(
        `つらい日は、無理に前を向かなくていい。今日は、ゆっくりで{いい}{から}{ね}。`,
        undefined,
        `つらい日は、無理をしなくていいん{だよ}。今日は、ゆっくりおやすみ。`,
        `つらい日は、無理しないで{ね}。10年前の自分が、ちゃんと応援してる{から}。`,
        `つらい日は、無理をしなくていいん{だよ}。100年先から、今日のあなたに「おやすみ」を言う{よ}。`,
      )
    case 'happy':
      return t(
        `今日の「うれしい」は、思い出すだけで笑っちゃうくらい懐かしい。覚えておいて{ね}。`,
        undefined,
        `今日の「うれしい」を、覚えておいて{ね}。年をとってからの宝物は、そういう日{だよ}。`,
        `うれしい日があるって聞けて、ほっとした。その気持ち、こっちも大事にする{よ}。`,
        `今日の「うれしい」は、100年たっても色あせない{よ}。ちゃんと覚えておいて{ね}。`,
      )
    case 'grateful':
      return t(
        `「ありがとう」と思える人がいる今日が、一番懐かしい。少しだけ、伝えてみて{ね}。`,
        undefined,
        `「ありがとう」と思える人がいる今日を、大事に{ね}。思ったときに、伝えてごらん。`,
        `「ありがとう」と思える人がいるんだ{ね}。……その人のこと、大事にして{ね}。`,
        `「ありがとう」と思える人がいる今日は、100年たっても一番の宝物{だよ}。伝えてごらん。`,
      )
    case 'tired':
      return t(
        `疲れた今日も、こっちから見ると少し懐かしい。今日は、ちゃんと休んで{ね}。`,
        undefined,
        `よくがんばってた{ね}、${name}。今日は、早めに休んで{ね}。`,
        `疲れるまでがんばってるんだ{ね}。……10年前の自分から、おつかれさま。`,
        `よくがんばってた{ね}、${name}。100年先から見ても、今日は大事な一日{だよ}。ゆっくり休んで{ね}。`,
      )
    case 'anxious':
      return t(
        `不安な夜も、こっちからはなぜか懐かしい。誰かの声を聞こうとした${name}を、覚えておく{よ}。`,
        undefined,
        `不安な夜も、時間がたつと懐かしい思い出になる{よ}。今夜の${name}のこと、覚え{てる}{から}{ね}。`,
        `不安な夜も、ちゃんと誰かの声を聞こうとしてるんだ{ね}。……こっちも、そうしてみる{よ}。`,
        `不安な夜も、100年たつと、静かな思い出になる{よ}。今夜の${name}のこと、覚え{てる}{から}{ね}。`,
      )
    case 'excited':
      return t(
        `${passion}その「わくわく」が、こっちからはまぶしいくらい懐かしい。思いきり味わって{ね}。`,
        undefined,
        `${passion}その「わくわく」が、こっちからはまぶしい{よ}。心ゆくまで味わって{ね}。`,
        `${passion}10年後の自分が、わくわくしてる。……それだけで、こっちは明日が楽しみになった{よ}。`,
        `${passion}その「わくわく」は、100年先から見てもまぶしい{よ}。思いきり味わって{ね}。`,
      )
    case 'unsure':
      return t(
        `わからないまま過ぎる今日も、ちゃんと懐かしい一日{だよ}。そのまま覚えておいて。`,
        undefined,
        `わからない日も、振り返れば懐かしい一日{だよ}。それでいいん{だよ}。`,
        `わからないままでも、ちゃんと10年たったんだ{ね}。……そっちの今日も、いつか懐かしくなる{よ}。`,
        `わからない日も、100年たつと、懐かしい一日になる{よ}。それでいいん{だよ}。`,
      )
    case 'calm':
    default:
      return t(
        `${who}過ごす何でもない今日が、こっちからは一番懐かしい。もう、懐かしくなり始めてる{よ}。`,
        undefined,
        `${who}過ごす何でもない一日が、年をとるほど懐かしいん{だよ}。今日も、もうそうなり始めてる{よ}。`,
        `${who}過ごす今日が、そっちにはあるんだ{ね}。……その今日も、いつか懐かしくなる{よ}。大事にして{ね}。`,
        `100年たっても、${who}過ごした何でもない日が、一番懐かしい{よ}。今日も、もうそうなり始めてる{よ}。`,
      )
  }
}
