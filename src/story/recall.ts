/** 振り返りを差しこむ確率 */
export const RECALL_CHANCE = 0.45

/**
 * nodeId と選んだ値から、振り返りの台詞を1つ選ぶ（無ければ null）。
 * 話題枠（topic）とその自由入力（topicText）は、その回の話題の recall を使う。
 */
export function recallFor(nodeId: string, value: string, c: CallContext): Variant | null {
  if (nodeId === 'topic' || nodeId === 'topicText') {
    const fn = TOPICS[c.topic]?.recall[nodeId === 'topicText' ? 'input' : value]
    return fn ? fn(c) : null
  }
  const pool = RECALL[`${nodeId}:${value}`]?.(c)
  if (!pool || pool.length === 0) return null
  return pool[Math.floor(Math.random() * pool.length)]
}
