/**
 * 「最近の◯◯」枠に入る話題（通話ごとにランダムで1つ）
 *
 * どの話題も同じ形：
 *   質問 → 3択（「あるよ」なら自由入力 → 返事／それ以外は返事）→ 次へ
 * 会話の往復の数は、話題によらず同じ。
 */
import type { CallContext } from './engine'
import { a, v, type Variant } from './text'

export interface Topic {
  /** 通話履歴に残す質問 */
  question: string
  ask: Variant
  /** 「あるよ」以外の2つの選択肢 */
  others: { label: string; value: string; reply: Variant[] }[]
  input: { prompt: string; placeholder: string; question: string }
  inputReply: (value: string) => Variant[]
  /** 振り返り（「確かにそうだった気がする」）。キーは選んだ値、自由入力は 'input' */
  recall: Record<string, (c: CallContext) => Variant>
}

